def _hollow(spec):
    """'40x40: 3 4 5' lines -> {'40x40x3': (h, b, t)}."""
    out = {}
    for line in spec.strip().splitlines():
        size, ts = line.split(":")
        h, b = (float(x) for x in size.split("x"))
        for t in ts.split():
            out[f"{size}x{t}"] = (h, b, float(t))
    return out


