def corner_radii(kind, t):
    """(outside, inside) corner radii of a square / rectangular hollow."""
    if kind == "hot":
        return 1.5 * t, 1.0 * t
    ro = 2.0 * t if t <= 6 else (2.5 * t if t <= 10 else 3.0 * t)
    return ro, ro - t


