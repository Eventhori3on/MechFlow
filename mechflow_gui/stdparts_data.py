#      A neck OD at weld, N1 hub at flange, B1 plate bore, d1 raised face,
#      f1 RF height, S neck wall, K bolt circle, L hole, n holes, bolt)
_EN_COLS = ("D", "C1", "C2", "H2", "H3", "A", "N1", "B1", "d1", "f1", "S",
            "K", "L", "n", "bolt")


def _en(rows):
    out = {}
    for line in rows.strip().splitlines():
        p = line.split()
        dn = int(p[0])
        vals = [float(x) for x in p[1:14]] + [int(p[14]), p[15]]
        out[dn] = dict(zip(_EN_COLS, vals))
    return out


