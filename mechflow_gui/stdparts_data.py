# ---------------------------------------------------------------- ASME B16.5
# NPS: (O, T, R raised face, X hub, n, hole, bolt circle, B slip-on bore,
#       B2 weld neck bore (std wall), H hub at weld = pipe OD,
#       L slip-on length, L2 weld neck length)   all inches
_AS_COLS = ("O", "T", "R", "X", "n", "hole", "BC", "B", "B2", "H", "L", "L2")


def _asme(rows):
    out = {}
    for line in rows.strip().splitlines():
        p = line.split()
        vals = [float(x) for x in p[1:]]
        d = dict(zip(_AS_COLS, vals))
        d["n"] = int(d["n"])
        out[p[0]] = d
    return out


